# V_dd 处理
# ============================================================
POP_PHASE_TOL = 1e-4
"""静态耦合（V_dd）丢弃判据的**无量纲**容差（rad）。判据（t78）：

    Θ = C · T · |V|² / max(|ΔE|, |V|)   ≥  POP_PHASE_TOL   → 保留

物理含义 = 该耦合在演化窗口 T 内累积的二阶相位（耦合自身的观测量）：
  · 共振极限（|ΔE| ≲ |V|）→ Θ = C·T·|V|        （Rabi 相位）
  · 远失谐极限（|ΔE| ≫ |V|）→ Θ = C·T·|V|²/Δ    （色散/vdW 相位）
判据只依赖 (|V|, |ΔE|, T)，与基组标度无关、与引擎无关 → hard / mixed 共用
（`coupling.static_phase_keep`），两引擎 V_dd 结果自动一致。

取 1e-4 的依据：实测两类耦合的 Θ 相差 3 个量级以上（共振 ~3.9 rad vs 双翻转
~5e-4 rad），故判据对取值在 1e-2~1e-3 区间**不敏感**；1e-4 属保守侧
（保留数 66~84 vs 50——多留弱耦合，不丢任何强耦合）。

取代（均已退役）：
  · `_VDD_MIN_FRAC = 1e-4`（幅度阈值 |V| ≥ 1e-4·max——随基组标度漂移，
    且管不住"|V| 大但远失谐"的元素，如 34.6 GHz 双翻转通道）；
  · mixed 对 `BW_OPT` 的借用（能量间隙阈值——与 |V| 无关，会误删共振弱耦合）。"""

_VDD_RWA_TOL_MHZ = 1.0
"""两场引擎（evolve_twofield）：V_dd **旋转系有效性**判据，|ΔE_rot−ΔE_lab| ≤ 1 MHz。
注意与 POP_PHASE_TOL 职责不同：它管的是"该元素在本征旋转系里相位是否成立"
（不成立即不可用），而非"效应大小够不够"——故保留独立。实测二者结论一致
（这类元素同时是 THz 级远失谐，Θ 也判它该丢）。"""

